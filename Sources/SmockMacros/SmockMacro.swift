import SwiftCompilerPlugin
import SwiftSyntax
import SwiftSyntaxBuilder
import SwiftSyntaxMacros

@main
struct SmockPlugin: CompilerPlugin {
    let providingMacros: [Macro.Type] = [
        MockableMacro.self
    ]
}

enum MockableError: Swift.Error, CustomStringConvertible {
    case notAProtocol
    case missingAccessorBlock

    var description: String {
        switch self {
        case .notAProtocol: "This macro can only be applied to protocol declarations"
        case .missingAccessorBlock: "Unexpectedly found no property accessor block"
        }
    }
}

public struct MockableMacro: PeerMacro {
    public static func expansion(
        of node: AttributeSyntax,
        providingPeersOf declaration: some DeclSyntaxProtocol,
        in context: some MacroExpansionContext
    ) throws -> [DeclSyntax] {
        // Ensure we are attached to a protocol
        guard let protocolDecl = declaration.as(ProtocolDeclSyntax.self) else {
            throw MockableError.notAProtocol
        }

        let protocolName = protocolDecl.name.text

        // Enumerate members to generate mocks, stubbers, etc.
        var genericTypes: [(type: String, inheritance: String)] = []
        var mocks: [String] = []
        var stubbers: [String] = []
        var verifiers: [String] = []
        for member in protocolDecl.memberBlock.members {
            if let associatedType = member.decl.as(AssociatedTypeDeclSyntax.self) {
                // Associated type -> Generic
                let inheritance = if let clause = associatedType.inheritanceClause {
                    "\(clause.description) & Sendable"
                } else {
                    ": Sendable"
                }
                genericTypes.append((associatedType.name.text, inheritance))
            } else if let function = member.decl.as(FunctionDeclSyntax.self) {
                // Function
                let impl = mockMethod(function)
                mocks.append(impl)

                let stub = stubMethod(function, protocolName: protocolName)
                stubbers.append(stub)

                let verifier = verifyMethod(function, protocolName: protocolName)
                verifiers.append(verifier)
            } else if let property = member.decl.as(VariableDeclSyntax.self) {
                // Property
                let impl = mockProperty(property)
                mocks.append(impl)

                let stub = stubProperty(property, protocolName: protocolName)
                stubbers.append(stub)

                let verifier = verifyProperty(property, protocolName: protocolName)
                verifiers.append(verifier)
            } else if let subscriptDecl = member.decl.as(SubscriptDeclSyntax.self) {
                // Subscript
                let impl = mockSubscript(subscriptDecl)
                mocks.append(impl)

                let stub = stubSubscript(subscriptDecl, protocolName: protocolName)
                stubbers.append(stub)

                let verifier = verifySubscript(subscriptDecl, protocolName: protocolName)
                verifiers.append(verifier)
            } else if let initializer = member.decl.as(InitializerDeclSyntax.self) {
                // Initializer - satisfy the compiler by generating init methods, but nothing else is needed
                let impl = mockInit(initializer)
                mocks.append(impl)
            }
        }

        // Translate associated types into generics
        let genericsOnly = if genericTypes.isEmpty { "" } else {
            "<\(genericTypes.map { $0.type }.joined(separator: ", "))>"
        }
        let genericsWithInheritance = if genericTypes.isEmpty { "" } else {
            "<\(genericTypes.map { "\($0.type)\($0.inheritance)" }.joined(separator: ", "))>"
        }

        let mockClassName = "\(protocolName)Mock"
        let mockClassImpl = """
        #if DEBUG
        /// This class is generated by the Mockable macro as a Smock instance which conforms to the \(protocolName) protocol.
        final nonisolated class \(mockClassName)\(genericsWithInheritance): Smock<any \(protocolName)>, \(protocolName), @unchecked Sendable {
            required public init(relaxed: Bool = false) {
                super.init(relaxed: relaxed)
            }
                
            \(mocks.joined(separator: "\n\n"))
        }
        #endif
        """

        let stubberClassName = "\(protocolName)StubBuilder"
        let stubberImpl = """
        #if DEBUG
        /// - Warning: This class is used by generated code and is not intended to be instantiated manually.
        nonisolated struct \(stubberClassName)\(genericsWithInheritance) {
            static var mock: Smock<any \(protocolName)> { SmockStatic[(any \(protocolName)).self] }
        
            let mock: Smock<any \(protocolName)>
            
            init(mock: Smock<any \(protocolName)>) {
                self.mock = mock
            }
                
            \(stubbers.joined(separator: "\n\n"))
        }
        #endif
        """

        let verifierClassName = "\(protocolName)Verifier"
        let verifierImpl = """
        #if DEBUG
        /// - Warning: This class is used by generated code and is not intended to be instantiated manually.
        nonisolated struct \(verifierClassName)\(genericsWithInheritance) {
            static var mock: Smock<any \(protocolName)> { SmockStatic[(any \(protocolName)).self] }
        
            let mock: Smock<any \(protocolName)>
            
            init(mock: Smock<any \(protocolName)>) {
                self.mock = mock
            }
        
            \(verifiers.joined(separator: "\n\n"))
        }
        #endif
        """

        let whenFunctions = """
        #if DEBUG
        /// Creates a stub builder associated with the given mock.
        func when\(genericsWithInheritance)(_ mock: \(mockClassName)\(genericsOnly)) -> \(stubberClassName)\(genericsOnly) {
            \(stubberClassName)(mock: mock)
        }

        /// Creates a stub builder associated with the given static mock.
        func when\(genericsWithInheritance)(_ static: \(mockClassName)\(genericsOnly).Type) -> \(stubberClassName)\(genericsOnly).Type {
            \(stubberClassName).self
        }
        #endif
        """

        let verifyFunctions = """
        #if DEBUG
        /// Creates a verifier associated with the given mock.
        func verify\(genericsWithInheritance)(_ mock: \(mockClassName)\(genericsOnly)) -> \(verifierClassName)\(genericsOnly) {
            \(verifierClassName)(mock: mock)
        }

        /// Creates a verifier associated with the given static mock.
        func verify\(genericsWithInheritance)(_ static: \(mockClassName)\(genericsOnly).Type) -> \(verifierClassName)\(genericsOnly).Type {
            \(verifierClassName).self
        }
        #endif
        """

        return [
            DeclSyntax(stringLiteral: mockClassImpl),
            DeclSyntax(stringLiteral: stubberImpl),
            DeclSyntax(stringLiteral: verifierImpl),
            DeclSyntax(stringLiteral: whenFunctions),
            DeclSyntax(stringLiteral: verifyFunctions)
        ]
    }

    // MARK: Mock members

    private static func mockMethod(_ function: FunctionDeclSyntax) -> String {
        // Extract function details
        let staticKeyword = function.isStatic ? "static " : ""
        let tryKeyword = function.isThrowing ? "try" : "try!"
        let awaitKeyword = function.isAsync ? " await" : ""

        // Apply parameter names as values when passing to getValue
        let paramNames = function.signature.parameterClause.parameters.map { parameter in
            parameter.secondName?.text ?? parameter.firstName.text
        }
        let paramValues = if paramNames.isEmpty { "" } else {
            ", params: \(paramNames.joined(separator: ", "))"
        }

        let signature = function.memberSignature // no line breaks
        return """
        /// A mocked protocol implementation which tracks calls and retrieves stubs.
        nonisolated \(staticKeyword)func \(signature) {
            trackCall("\(signature)"\(paramValues))
            return \(tryKeyword)\(awaitKeyword) getValue(for: "\(signature)"\(paramValues))
        }
        """
    }

    private static func mockProperty(_ property: VariableDeclSyntax) -> String {
        // Protocols will only have 1 binding per declaration
        guard
            let binding = property.bindings.first,
            let identifier = binding.pattern.as(IdentifierPatternSyntax.self)?.identifier.text,
            let type = binding.typeAnnotation?.type.trimmedDescription
        else {
            return ""
        }

        let (isThrowing, isAsync, getClause, setClause) = binding.accessorBlock.extractAll()

        let staticKeyword = property.isStatic ? "static " : ""
        let tryKeyword = isThrowing ? "try" : "try!"
        let awaitKeyword = isAsync ? " await" : ""

        let getter = """
            \(getClause) {
                trackCall("\(identifier)")
                return \(tryKeyword)\(awaitKeyword) getValue(for: "\(identifier)")
            }
        """

        let setter = if let setClause {
            """
            
                \(setClause) {
                    trackCall("\(identifier)", params: newValue)
                }
            """
        } else {
            ""
        }

        return """
        /// A mocked protocol implementation which tracks calls and retrieves stubs.
        nonisolated \(staticKeyword)var \(identifier): \(type) {
        \(getter)\(setter)
        }
        """
    }

    private static func mockInit(_ initializer: InitializerDeclSyntax) -> String {
        let signature = initializer.trimmedDescription
        return """
        /// Protocol-required initializer. Generally should not be used in favor of `init(relaxed:)`.
        convenience \(signature) {
            self.init(relaxed: false)
        }
        """
    }

    private static func mockSubscript(_ subscriptDecl: SubscriptDeclSyntax) -> String {
        // Apply parameter names as values when passing to getValue
        let paramNames = subscriptDecl.parameterClause.parameters.map { parameter in
            parameter.secondName?.text ?? parameter.firstName.text
        }
        let paramValues = if paramNames.isEmpty {
            ""
        } else {
            ", params: \(paramNames.joined(separator: ", "))"
        }

        let (isThrowing, isAsync, getClause, setClause) = subscriptDecl.accessorBlock.extractAll()

        let staticKeyword = subscriptDecl.isStatic ? "static " : ""
        let tryKeyword = isThrowing ? "try" : "try!"
        let awaitKeyword = isAsync ? " await" : ""

        let signature = subscriptDecl.memberSignature // no line breaks

        let getter = """
            \(getClause) {
                trackCall("\(signature)"\(paramValues))
                return \(tryKeyword)\(awaitKeyword) getValue(for: "\(signature)"\(paramValues))
            }
        """

        // NOTE: newValue is appended to the subscript params for matching (see Verifier)
        let setter = if let setClause {
            """
            
                \(setClause) {
                    trackCall("\(signature)"\(paramValues), newValue)
                }
            """
        } else {
            ""
        }


        return """
        /// A mocked protocol implementation which tracks calls and retrieves stubs.
        nonisolated \(staticKeyword)\(signature) {
        \(getter)\(setter)
        }
        """
    }

    // MARK: Stubber members

    private static func stubMethod(_ function: FunctionDeclSyntax, protocolName: String) -> String {
        let parameters = function.signature.parameterClause.parameters
        let returnType = function.signature.returnClause?.type.trimmedDescription ?? "Void"

        let paramMatchers: String = parameters
            .map {
                let secondName = if let name = $0.secondName { " \(name.text)" } else { "" }
                var type = $0.type.cleanedDescription()
                // Stub varargs as arrays
                if $0.ellipsis != nil {
                    type = "[\(type)]"
                }
                return "\($0.firstName.text)\(secondName): ArgumentMatcher<\(type)>"
            }
            .joined(separator: ", ")

        // Pass parameters if present
        let paramNames = parameters.map { parameter in
            parameter.secondName?.text ?? parameter.firstName.text
        }
        let paramCapture = if paramNames.isEmpty { "" } else {
            ", params: \(paramNames.joined(separator: ", "))"
        }

        // Determine builder type (e.g. async/throwing)
        var builderType = "ReturnBuilder<any \(protocolName), \(returnType)>"
        if function.isThrowing {
            builderType = "Throwing" + builderType
        }
        if function.isAsync {
            builderType = "Async" + builderType
        }

        let staticKeyword = function.isStatic ? "static " : ""

        let signature = function.memberSignature // includes generics, etc.
        let name = if let parensIndex = signature.firstIndex(of: "(") {
            String(signature.prefix(upTo: parensIndex))
        } else {
            signature
        }

        let whereClause = if let clause = function.genericWhereClause {
            " \(clause.description)"
        } else {
            ""
        }

        let matcherComment = parameters.isEmpty ? "" : "accepts argument matchers for each parameter and "
        return """
        /// A duplicate protocol implementation which \(matcherComment)returns a stub builder.
        \(staticKeyword)func \(name)(\(paramMatchers)) -> \(builderType)\(whereClause) {
            \(builderType)(mock: mock, signature: "\(signature)"\(paramCapture))
        }
        """
    }

    private static func stubProperty(_ property: VariableDeclSyntax, protocolName: String) -> String {
        guard
            let binding = property.bindings.first,
            let identifier = binding.pattern.as(IdentifierPatternSyntax.self)?.identifier.text,
            let type = binding.typeAnnotation?.type.trimmedDescription
        else {
            return ""
        }

        let staticKeyword = property.isStatic ? "static " : ""
        let (isThrowing, isAsync) = binding.accessorBlock.extractEffects()

        // Determine builder type (e.g. async/throwing)
        var builderType = "ReturnBuilder<any \(protocolName), \(type)>"
        if isThrowing {
            builderType = "Throwing" + builderType
        }
        if isAsync {
            builderType = "Async" + builderType
        }

        return """
        /// A duplicate protocol implementation which returns a stub builder.
        \(staticKeyword)var \(identifier): \(builderType) {
            \(builderType)(mock: mock, signature: "\(identifier)")
        }
        """
    }

